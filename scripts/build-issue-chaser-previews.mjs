import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const serviceRoot = path.resolve(process.env.SERVICE_REPOSITORY_ROOT || path.dirname(root), "usecase-issue-chaser");
const { normalizeRow } = require(path.join(serviceRoot, "lib/safety-sheet.js"));
const { issueCaption, dailySummary } = require(path.join(serviceRoot, "lib/messages.js"));
const nowMs = Date.parse("2026-09-29T02:00:00Z");
const previews = [
  { value: "wohhup_issue_format", bands: ["P1", "P2", "P3"], summary: "Wohhup P1/P2/P3. Reminders repeat every 3 hours, 24 hours or 7 days respectively; this preserves the existing flow." },
  { value: "cccc_issue_format", bands: ["A1", "A2", "B", "C"], summary: "CCCC A1/A2/B/C. First reminders: next eligible check, after 24 hours, 3 days or 7 days; every band then repeats after a 3-hour successful-send cooldown. B's displayed target remains 1–3 days." },
].map(({ value, bands, summary }) => {
  const issues = bands.map((Severity, index) => normalizeRow({ "S/N": String(42 + index), Severity, Status: "open", "Created Timestamp": "2026-09-29T00:00:00Z", Date: "2026-09-29", Location: "Zone 1", Description: "Keep the access route clear." }, value));
  return {
    service: "issueChaser", column: "issues_format", value, summary, kind: "message",
    bubbles: [
      { caption: "Individual reminder", text: issueCaption(issues[0], { nowMs }) },
      { caption: "Daily-open count summary", text: dailySummary(issues, "2026-09-29") },
    ],
    isFallback: value === "wohhup_issue_format",
    source: "Issue Chaser lib/messages.js and domain/issue-format-registry.js",
  };
});
const output = "// Generated by scripts/build-issue-chaser-previews.mjs using the Issue Chaser message builders.\n" +
  "import type { FormatterPreview } from './message-previews';\n\n" +
  `export const ISSUE_FORMAT_PREVIEWS: FormatterPreview[] = ${JSON.stringify(previews, null, 2)};\n`;
writeFileSync(process.env.ISSUE_PREVIEWS_OUT || path.join(root, "lib/issue-chaser-previews.generated.ts"), output);
